"""Deterministic unsigned RPM v4 packages from declared Linux payloads."""

import gzip
import hashlib
import json
import io
from pathlib import Path, PurePosixPath
import re
import shutil
import stat
import struct
import sys
import tarfile
import tempfile

from electron.private.update import _version


# RPM v4 types and tags: rpm-4.20.0 include/rpm/rpmtag.h.
_INT16, _INT32, _STRING, _BIN, _STRINGS, _I18N = 3, 4, 6, 7, 8, 9


def header(tags, region):
    data, indexes = bytearray(), []
    for tag, (kind, values) in sorted(tags.items()):
        if kind in (_INT16, _INT32):
            alignment, code = (2, "H") if kind == _INT16 else (4, "I")
            data.extend(b"\0" * (-len(data) % alignment))
            encoded = struct.pack(">" + code * len(values), *values)
            count = len(values)
        elif kind == _BIN:
            encoded, count = values, len(values)
        else:
            if kind == _STRING:
                values = [values]
            if any("\0" in value for value in values):
                raise ValueError("RPM strings cannot contain NUL")
            encoded, count = b"".join(value.encode("utf-8") + b"\0" for value in values), len(values)
        indexes.append(struct.pack(">IIII", tag, kind, len(data), count))
        data.extend(encoded)
    count = len(indexes) + 1
    trailer = struct.pack(">IIiI", region, _BIN, -16 * count, 16)
    indexes.insert(0, struct.pack(">IIII", region, _BIN, len(data), 16))
    data.extend(trailer)
    return b"\x8e\xad\xe8\x01\0\0\0\0" + struct.pack(">II", count, len(data)) + b"".join(indexes) + data


def requirements(values):
    result = {}
    for value in values:
        match = re.fullmatch(r"([^\s<>=\x00]+)(?: (<=|>=|=|<|>) ([A-Za-z0-9][A-Za-z0-9._+~:^%-]*))?", value)
        if not match:
            raise ValueError("Invalid RPM requirement")
        name, operator, version = match.groups()
        if name.startswith("rpmlib("):
            raise ValueError("RPM format requirements are generated by the packager")
        result[(name, version or "")] = {None: 0, "<": 2, ">": 4, "=": 8, "<=": 10, ">=": 12}[operator]
    for name, version in [("CompressedFileNames", "3.0.4-1"), ("PayloadFilesHavePrefix", "4.0-1"), ("FileDigests", "4.6.0-1")]:
        result[("rpmlib(" + name + ")", version)] = (1 << 24) | 10
    return [(name, version, flags) for (name, version), flags in sorted(result.items())]


class Payload:
    def __init__(self, destination):
        self.destination, self.size, self.digest = destination, 0, hashlib.sha256()

    def write(self, data):
        self.destination.write(data)
        self.digest.update(data)
        self.size += len(data)

    def member(self, name, number, mode, size, source):
        encoded = ("./" + name).encode("utf-8") + b"\0"
        fields = [number, mode, 0, 0, 2 if stat.S_ISDIR(mode) else 1, 0, size, 0, 0, 0, 0, len(encoded), 0]
        self.write(b"070701" + b"".join(f"{value:08x}".encode("ascii") for value in fields) + encoded)
        self.write(b"\0" * (-(110 + len(encoded)) % 4))
        remaining = size
        digest = hashlib.sha256()
        while remaining:
            data = source.read(min(1024**2, remaining))
            if not data:
                raise ValueError("Truncated RPM payload input")
            self.write(data)
            digest.update(data)
            remaining -= len(data)
        self.write(b"\0" * (-size % 4))
        return digest.hexdigest()

    def finish(self):
        name = b"TRAILER!!!\0"
        fields = [0] * 11 + [len(name), 0]
        self.write(b"070701" + b"".join(f"{value:08x}".encode("ascii") for value in fields) + name)
        self.write(b"\0" * (-self.size % 512))


def build_rpm(payload, package_json, package_name, architecture, release, summary, description,
              license, requires, maintainer, output, prein="", postin="", preun="", postun=""):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._+-]*", package_name):
        raise ValueError("Invalid RPM package name")
    if architecture not in ("x86_64", "aarch64"):
        raise ValueError("Unsupported RPM architecture")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._+~]*", release):
        raise ValueError("Invalid RPM release")
    for value in [summary, description, license]:
        if not value or "\0" in value:
            raise ValueError("RPM summary, description and license must be nonempty")
    version = _version(json.loads(Path(package_json).read_text(encoding="utf-8"))["version"]).split("+", 1)[0].replace("-", "~", 1)
    dependencies = requirements(requires)
    if any([prein, postin, preun, postun]):
        dependencies.append(("/bin/sh", "", 0))
    files = []
    with tempfile.TemporaryDirectory() as temporary:
        compressed = Path(temporary) / "payload.gz"
        with tarfile.open(payload, "r:gz") as archive, compressed.open("wb") as destination:
            with gzip.GzipFile(filename="", fileobj=destination, mode="wb", mtime=0, compresslevel=9) as stream:
                contents = Payload(stream)
                seen = set()
                for number, entry in enumerate(archive, 1):
                    name = entry.name.rstrip("/")
                    path = PurePosixPath(name)
                    if not path.parts or path.is_absolute() or ".." in path.parts or str(path) != name or "\0" in name or name in seen:
                        raise ValueError("Invalid or duplicate RPM payload path")
                    seen.add(name)
                    if entry.size > 0xffffffff:
                        raise ValueError("RPM v4 payload files must be smaller than 4 GiB")
                    if entry.isfile():
                        mode, size, link = stat.S_IFREG | entry.mode, entry.size, ""
                        with archive.extractfile(entry) as source:
                            digest = contents.member(name, number, mode, size, source)
                    elif entry.isdir():
                        mode, size, link, digest = stat.S_IFDIR | entry.mode, 0, "", ""
                        contents.member(name, number, mode, 0, None)
                    elif entry.issym():
                        link = entry.linkname
                        target = PurePosixPath(link)
                        if target.is_absolute() or "\0" in link:
                            raise ValueError("Invalid RPM symlink target")
                        depth = len(path.parts) - 1
                        for part in target.parts:
                            depth += -1 if part == ".." else 0 if part == "." else 1
                            if depth < 0:
                                raise ValueError("RPM symlink escapes payload")
                        mode, size, digest = stat.S_IFLNK | 0o777, len(link.encode("utf-8")), ""
                        contents.member(name, number, mode, size, io.BytesIO(link.encode("utf-8")))
                    else:
                        raise ValueError("RPM payload requires regular files, directories or symlinks")
                    files.append(("/" + name, mode, size, link, digest, number))
                contents.finish()
        if not files:
            raise ValueError("RPM payload is empty")
        directories = sorted({str(PurePosixPath(name).parent).rstrip("/") + "/" for name, *_ in files})
        indexes = {name: index for index, name in enumerate(directories)}
        count = len(files)
        if sum(file[2] for file in files) > 0xffffffff:
            raise ValueError("RPM v4 package size must be smaller than 4 GiB")
        with compressed.open("rb") as source:
            payload_digest = hashlib.file_digest(source, "sha256").hexdigest()
        tags = {
            100: (_STRINGS, ["C"]), 1000: (_STRING, package_name), 1001: (_STRING, version),
            1002: (_STRING, release), 1004: (_I18N, [summary]), 1005: (_I18N, [description]),
            1006: (_INT32, [0]), 1007: (_STRING, "bazel"), 1009: (_INT32, [sum(file[2] for file in files)]),
            1014: (_STRING, license), 1015: (_STRING, maintainer), 1016: (_I18N, ["Applications"]),
            1021: (_STRING, "linux"), 1022: (_STRING, architecture),
            1028: (_INT32, [file[2] for file in files]), 1030: (_INT16, [file[1] for file in files]),
            1033: (_INT16, [0] * count), 1034: (_INT32, [0] * count),
            1035: (_STRINGS, [file[4] for file in files]), 1036: (_STRINGS, [file[3] for file in files]),
            1037: (_INT32, [0] * count), 1039: (_STRINGS, ["root"] * count), 1040: (_STRINGS, ["root"] * count),
            1044: (_STRING, "(none)"), 1045: (_INT32, [0x1ff] * count),
            1047: (_STRINGS, [package_name]), 1048: (_INT32, [item[2] for item in dependencies]),
            1049: (_STRINGS, [item[0] for item in dependencies]), 1050: (_STRINGS, [item[1] for item in dependencies]),
            1095: (_INT32, [1] * count), 1096: (_INT32, [file[5] for file in files]), 1097: (_STRINGS, [""] * count),
            1112: (_INT32, [8]), 1113: (_STRINGS, [version + "-" + release]),
            1116: (_INT32, [indexes[str(PurePosixPath(file[0]).parent).rstrip("/") + "/"] for file in files]),
            1117: (_STRINGS, [PurePosixPath(file[0]).name for file in files]), 1118: (_STRINGS, directories),
            1124: (_STRING, "cpio"), 1125: (_STRING, "gzip"), 1126: (_STRING, "9"),
            5011: (_INT32, [8]), 5062: (_STRING, "utf-8"),
            5092: (_STRINGS, [payload_digest]), 5093: (_INT32, [8]), 5097: (_STRINGS, [contents.digest.hexdigest()]),
        }
        for tag, source in [(1023, prein), (1024, postin), (1025, preun), (1026, postun)]:
            if source:
                tags[tag] = (_STRING, Path(source).read_text(encoding="utf-8"))
                tags[tag + 62] = (_STRINGS, ["/bin/sh"])
        metadata = header(tags, 63)
        md5 = hashlib.md5(metadata, usedforsecurity=False)
        with compressed.open("rb") as source:
            for data in iter(lambda: source.read(1024**2), b""):
                md5.update(data)
        signature = header({
            269: (_STRING, hashlib.sha1(metadata, usedforsecurity=False).hexdigest()),
            273: (_STRING, hashlib.sha256(metadata).hexdigest()),
            1000: (_INT32, [len(metadata) + compressed.stat().st_size]),
            1004: (_BIN, md5.digest()),
        }, 62)
        name = (package_name + "-" + version + "-" + release).encode("utf-8")[:65]
        lead = struct.pack(">4sBBHH66sHH16s", b"\xed\xab\xee\xdb", 3, 0, 0, 1, name, 1, 5, b"\0" * 16)
        with Path(output).open("wb") as destination, compressed.open("rb") as source:
            destination.write(lead + signature + b"\0" * (-len(signature) % 8) + metadata)
            shutil.copyfileobj(source, destination, 1024**2)


if __name__ == "__main__":
    build_rpm(output=sys.argv[2], **json.loads(Path(sys.argv[1]).read_text(encoding="utf-8")))
